-- ============================================================================
-- SnowHealth CI/CD — one-time account setup (run as ACCOUNTADMIN)
--
-- Single account, two environments:
--   DEV  → DEV_SNOWHEALTH_ML_DB  (deployed by SVC_SNOWHEALTH_GH_DEV)
--   PROD → PRD_SNOWHEALTH_ML_DB  (deployed by SVC_SNOWHEALTH_GH_PROD)
--
-- Each GitHub environment (dev / prod) authenticates via OIDC to its own
-- service user, which can only use its own deployer role. Compute
-- (COMPUTE_WH, SNOWHEALTH_COMPUTE_POOL) is shared; data is not.
--
--   snow sql -f scripts/setup_cicd.sql -c <admin_connection>
--
-- Idempotent. Re-running is safe.
-- ============================================================================
USE ROLE ACCOUNTADMIN;

-- OIDC subjects below use GitHub's immutable format for this repo:
--   repo:<owner>@<owner_id>/<repo>@<repo_id>:environment:<env>
-- (prefix from: gh api repos/<owner>/<repo>/actions/oidc/customization/sub)

-- ── Deployer roles ──────────────────────────────────────────────────────────
CREATE ROLE IF NOT EXISTS SNOWHEALTH_DEV_DEPLOYER
    COMMENT = 'Deploys SnowHealth feature store + ML pipeline to DEV_SNOWHEALTH_ML_DB';
CREATE ROLE IF NOT EXISTS SNOWHEALTH_PROD_DEPLOYER
    COMMENT = 'Deploys SnowHealth feature store + ML pipeline to PRD_SNOWHEALTH_ML_DB';
-- Roll up so admins (and the interactive notebooks) keep access
GRANT ROLE SNOWHEALTH_DEV_DEPLOYER TO ROLE SYSADMIN;
GRANT ROLE SNOWHEALTH_PROD_DEPLOYER TO ROLE SYSADMIN;

-- ── Shared compute ──────────────────────────────────────────────────────────
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE SNOWHEALTH_DEV_DEPLOYER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE SNOWHEALTH_PROD_DEPLOYER;
GRANT USAGE, MONITOR ON COMPUTE POOL SNOWHEALTH_COMPUTE_POOL TO ROLE SNOWHEALTH_DEV_DEPLOYER;
GRANT USAGE, MONITOR ON COMPUTE POOL SNOWHEALTH_COMPUTE_POOL TO ROLE SNOWHEALTH_PROD_DEPLOYER;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SNOWHEALTH_DEV_DEPLOYER;
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SNOWHEALTH_PROD_DEPLOYER;

-- ── PROD database (new, owned end-to-end by the PROD deployer) ──────────────
CREATE DATABASE IF NOT EXISTS PRD_SNOWHEALTH_ML_DB
    COMMENT = 'SnowHealth Demand Forecasting (PROD)';
CREATE SCHEMA IF NOT EXISTS PRD_SNOWHEALTH_ML_DB.SNOWHEALTH_RAW
    COMMENT = 'Raw transaction data (PROD) — loaded by ingestion, not CI';
CREATE SCHEMA IF NOT EXISTS PRD_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS
    COMMENT = 'Model registry and pipeline objects (PROD)';
GRANT OWNERSHIP ON DATABASE PRD_SNOWHEALTH_ML_DB TO ROLE SNOWHEALTH_PROD_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL SCHEMAS IN DATABASE PRD_SNOWHEALTH_ML_DB TO ROLE SNOWHEALTH_PROD_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN DATABASE PRD_SNOWHEALTH_ML_DB TO ROLE SNOWHEALTH_PROD_DEPLOYER COPY CURRENT GRANTS;

-- ── DEV database (existing; shared with the interactive notebooks) ──────────
-- Deployer owns only what the pipeline manages; notebook objects stay with
-- ACCOUNTADMIN (which inherits the deployer role, so nothing is lost).
GRANT USAGE, CREATE SCHEMA ON DATABASE DEV_SNOWHEALTH_ML_DB TO ROLE SNOWHEALTH_DEV_DEPLOYER;
GRANT USAGE ON SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_RAW TO ROLE SNOWHEALTH_DEV_DEPLOYER;
GRANT SELECT ON TABLE DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_RAW.SNOWHEALTH_DEMAND_TRANSACTIONS TO ROLE SNOWHEALTH_DEV_DEPLOYER;
GRANT OWNERSHIP ON SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;

-- Hand over the objects the CI pipeline manages (no-ops on a fresh account).
-- Task ownership can only move while the DAG is suspended.
ALTER TASK IF EXISTS DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS.SNOWHEALTH_PIPELINE_ROOT SUSPEND;
GRANT OWNERSHIP ON ALL TASKS IN SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL DCM PROJECTS IN SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
-- Code bundles are NOTEBOOK PROJECT objects
GRANT OWNERSHIP ON ALL NOTEBOOK PROJECTS IN SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL STAGES IN SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON TABLE DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS.SNOWHEALTH_PIPELINE_FEATURES TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON TABLE DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS.SNOWHEALTH_PIPELINE_DEPLOY_LOG TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON MODEL DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_MODELS.SNOWHEALTH_PIPELINE_MODEL TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
-- Declarative feature store schema (created by `snow feature init`)
GRANT OWNERSHIP ON SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_PIPELINE_FS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_PIPELINE_FS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL DYNAMIC TABLES IN SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_PIPELINE_FS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON ALL VIEWS IN SCHEMA DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_PIPELINE_FS TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
-- Feature store metadata tags (no bulk OWNERSHIP grant exists for tags)
GRANT OWNERSHIP ON TAG DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_PIPELINE_FS.SNOWML_FEATURE_STORE_OBJECT TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON TAG DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_PIPELINE_FS.SNOWML_FEATURE_VIEW_METADATA TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;
GRANT OWNERSHIP ON TAG DEV_SNOWHEALTH_ML_DB.SNOWHEALTH_PIPELINE_FS.SNOWML_FEATURE_STORE_ENTITY_SNOWHEALTH_TRANSACTION TO ROLE SNOWHEALTH_DEV_DEPLOYER COPY CURRENT GRANTS;

-- ── Service users (OIDC, one per GitHub environment) ────────────────────────
CREATE USER IF NOT EXISTS SVC_SNOWHEALTH_GH_DEV
    TYPE = SERVICE
    DEFAULT_ROLE = SNOWHEALTH_DEV_DEPLOYER
    DEFAULT_WAREHOUSE = COMPUTE_WH
    COMMENT = 'GitHub Actions (environment: dev) — snowflake-ml-hcls-demo';
CREATE USER IF NOT EXISTS SVC_SNOWHEALTH_GH_PROD
    TYPE = SERVICE
    DEFAULT_ROLE = SNOWHEALTH_PROD_DEPLOYER
    DEFAULT_WAREHOUSE = COMPUTE_WH
    COMMENT = 'GitHub Actions (environment: prod) — snowflake-ml-hcls-demo';

ALTER USER SVC_SNOWHEALTH_GH_DEV SET WORKLOAD_IDENTITY = (
    TYPE = OIDC
    ISSUER = 'https://token.actions.githubusercontent.com'
    SUBJECT = 'repo:sfc-gh-trasmith@256389544/snowflake-ml-hcls-demo@1407872279:environment:dev');
ALTER USER SVC_SNOWHEALTH_GH_PROD SET WORKLOAD_IDENTITY = (
    TYPE = OIDC
    ISSUER = 'https://token.actions.githubusercontent.com'
    SUBJECT = 'repo:sfc-gh-trasmith@256389544/snowflake-ml-hcls-demo@1407872279:environment:prod');

GRANT ROLE SNOWHEALTH_DEV_DEPLOYER TO USER SVC_SNOWHEALTH_GH_DEV;
GRANT ROLE SNOWHEALTH_PROD_DEPLOYER TO USER SVC_SNOWHEALTH_GH_PROD;

-- Account-level network policy blocks GitHub-hosted runners; scope an
-- allow-list policy (managed rule SNOWFLAKE.NETWORK_SECURITY.GITHUBACTIONS_GLOBAL)
-- to these two users only.
CREATE NETWORK POLICY IF NOT EXISTS GITHUB_ACTIONS_POLICY
    ALLOWED_NETWORK_RULE_LIST = ('SNOWFLAKE.NETWORK_SECURITY.GITHUBACTIONS_GLOBAL')
    COMMENT = 'Allow GitHub Actions runners via managed network rule';
ALTER USER SVC_SNOWHEALTH_GH_DEV SET NETWORK_POLICY = GITHUB_ACTIONS_POLICY;
ALTER USER SVC_SNOWHEALTH_GH_PROD SET NETWORK_POLICY = GITHUB_ACTIONS_POLICY;
